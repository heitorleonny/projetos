-- ============================================================================
-- 27 — Métricas personalizadas da federação (painel de métricas)
--
-- Decisões de Heitor (12/11/2026): todos os usuários da federação VEEM o painel;
-- só `admin` ativo da federação CRIA, edita, tira do painel, arquiva e exclui.
-- A métrica é DADO (uma definição JSON com expressão do catálogo fechado), nunca
-- código: o backend revalida a expressão a cada leitura e calcula sozinho.
--
-- Migração aditiva: tabela nova, sem tocar em dado existente.
--
-- Camadas, como no resto do portal:
--   * SELECT: tenant pelo claim `federacao_id` (mesmo idioma de 07/20);
--   * INSERT/UPDATE/DELETE: tenant do claim E papel do BANCO
--     (`eh_admin_da_federacao`, de 13). Admin rebaixado com token velho não escreve;
--   * DELETE só de métrica já arquivada (exclusão definitiva é o segundo passo);
--   * GRANT por coluna: `federacao_id`, `criado_por`, `versao` e datas não são
--     editáveis pelo cliente depois da criação.
-- ============================================================================

BEGIN;

CREATE TABLE IF NOT EXISTS public.metrica_personalizada (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    federacao_id bigint NOT NULL REFERENCES public.federacao(id) ON DELETE CASCADE,
    nome text NOT NULL CHECK (length(btrim(nome)) BETWEEN 3 AND 80),
    descricao text CHECK (descricao IS NULL OR length(descricao) <= 300),
    visual text NOT NULL DEFAULT 'ranking' CHECK (visual IN ('ranking', 'valor', 'serie')),
    definicao jsonb NOT NULL CHECK (
        jsonb_typeof(definicao) = 'object'
        AND jsonb_typeof(definicao->'expressao') = 'string'
        AND length(definicao->>'expressao') BETWEEN 1 AND 300
        AND (definicao->>'ano')::integer BETWEEN 2000 AND 2100
        AND pg_column_size(definicao) <= 4096
    ),
    no_painel boolean NOT NULL DEFAULT true,
    ordem integer NOT NULL DEFAULT 0 CHECK (ordem BETWEEN 0 AND 10000),
    versao integer NOT NULL DEFAULT 1,
    criado_por uuid NOT NULL REFERENCES auth.users(id),
    atualizado_por uuid REFERENCES auth.users(id),
    criado_em timestamptz NOT NULL DEFAULT now(),
    atualizado_em timestamptz NOT NULL DEFAULT now(),
    arquivada_em timestamptz
);

COMMENT ON TABLE public.metrica_personalizada IS
    'Métricas personalizadas da federação. Não são indicadores oficiais do MEJ; não alteram cluster, SDE ou tracking.';

-- Nome único entre as métricas ativas da federação (arquivar libera o nome).
CREATE UNIQUE INDEX IF NOT EXISTS uq_metrica_nome_ativa
    ON public.metrica_personalizada (federacao_id, lower(btrim(nome)))
    WHERE arquivada_em IS NULL;
CREATE INDEX IF NOT EXISTS idx_metrica_tenant_ordem
    ON public.metrica_personalizada (federacao_id, arquivada_em, ordem, id);

-- Versão e datas são do banco: o cliente não as escolhe.
CREATE OR REPLACE FUNCTION public.metrica_personalizada_antes_de_gravar()
RETURNS trigger LANGUAGE plpgsql SET search_path = pg_catalog, public AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        NEW.versao := 1;
        NEW.criado_em := now();
        NEW.atualizado_em := now();
        NEW.arquivada_em := NULL;
        -- Teto por federação, contado entre as ativas visíveis ao próprio admin.
        IF (SELECT count(*) FROM public.metrica_personalizada m
             WHERE m.federacao_id = NEW.federacao_id AND m.arquivada_em IS NULL) >= 50 THEN
            RAISE EXCEPTION 'A federação já tem 50 métricas ativas. Arquive alguma antes de criar outra.'
                USING ERRCODE = '23514';
        END IF;
        RETURN NEW;
    END IF;
    IF NEW.federacao_id IS DISTINCT FROM OLD.federacao_id OR NEW.criado_por IS DISTINCT FROM OLD.criado_por THEN
        RAISE EXCEPTION 'Federação e autoria da métrica não mudam.' USING ERRCODE = '42501';
    END IF;
    NEW.criado_em := OLD.criado_em;
    NEW.atualizado_em := now();
    NEW.versao := OLD.versao + CASE WHEN NEW.definicao IS DISTINCT FROM OLD.definicao THEN 1 ELSE 0 END;
    RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS trg_metrica_personalizada_gravar ON public.metrica_personalizada;
CREATE TRIGGER trg_metrica_personalizada_gravar
    BEFORE INSERT OR UPDATE ON public.metrica_personalizada
    FOR EACH ROW EXECUTE FUNCTION public.metrica_personalizada_antes_de_gravar();
REVOKE EXECUTE ON FUNCTION public.metrica_personalizada_antes_de_gravar() FROM PUBLIC, anon, authenticated;

ALTER TABLE public.metrica_personalizada ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.metrica_personalizada FORCE ROW LEVEL SECURITY;

REVOKE ALL ON public.metrica_personalizada FROM PUBLIC, anon, authenticated;
GRANT SELECT, DELETE ON public.metrica_personalizada TO authenticated;
GRANT INSERT (federacao_id, nome, descricao, visual, definicao, no_painel, ordem, criado_por)
    ON public.metrica_personalizada TO authenticated;
GRANT UPDATE (nome, descricao, visual, definicao, no_painel, ordem, atualizado_por, arquivada_em)
    ON public.metrica_personalizada TO authenticated;

DROP POLICY IF EXISTS metrica_tenant_select ON public.metrica_personalizada;
CREATE POLICY metrica_tenant_select ON public.metrica_personalizada
    FOR SELECT TO authenticated
    USING (federacao_id = nullif(auth.jwt()->>'federacao_id', '')::bigint);

DROP POLICY IF EXISTS metrica_admin_insert ON public.metrica_personalizada;
CREATE POLICY metrica_admin_insert ON public.metrica_personalizada
    FOR INSERT TO authenticated
    WITH CHECK (
        federacao_id = nullif(auth.jwt()->>'federacao_id', '')::bigint
        AND public.eh_admin_da_federacao(federacao_id)
        AND criado_por = auth.uid()
    );

DROP POLICY IF EXISTS metrica_admin_update ON public.metrica_personalizada;
CREATE POLICY metrica_admin_update ON public.metrica_personalizada
    FOR UPDATE TO authenticated
    USING (
        federacao_id = nullif(auth.jwt()->>'federacao_id', '')::bigint
        AND public.eh_admin_da_federacao(federacao_id)
    )
    WITH CHECK (
        federacao_id = nullif(auth.jwt()->>'federacao_id', '')::bigint
        AND public.eh_admin_da_federacao(federacao_id)
        AND (atualizado_por IS NULL OR atualizado_por = auth.uid())
    );

DROP POLICY IF EXISTS metrica_admin_delete ON public.metrica_personalizada;
CREATE POLICY metrica_admin_delete ON public.metrica_personalizada
    FOR DELETE TO authenticated
    USING (
        federacao_id = nullif(auth.jwt()->>'federacao_id', '')::bigint
        AND public.eh_admin_da_federacao(federacao_id)
        AND arquivada_em IS NOT NULL
    );

COMMIT;

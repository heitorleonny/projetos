-- ============================================================================
-- 10 — Ingestão: proveniência (`ingestao_carga`) e staging (`ingestao_staging_ej`)
--
-- Até aqui o dado entrava por um fluxo de n8n fora do repositório, sem teste e
-- sem registro. Daqui em diante toda carga das exportações do Portal BJ passa
-- por `app/ingestao/` e deixa rastro em duas tabelas:
--
--   ingestao_carga       uma linha por arquivo processado — quem, quando, qual
--                        arquivo (hash), qual escopo, quantas linhas, e se deu
--                        certo. Inclusive as cargas que falharam.
--   ingestao_staging_ej  a linha da planilha COMO VEIO, antes de qualquer
--                        transformação, pendurada na carga que a trouxe.
--
-- OS QUATRO GANHOS, e são eles que justificam guardar tudo isto:
--
--   1. Reprocessar sem pedir o arquivo de novo. Se uma regra de transformação
--      mudar (a do CSAT sem coleta, por exemplo), o dado bruto já está aqui.
--   2. Auditar de onde veio cada número. Todo valor em `monitoramento` tem uma
--      linha de staging com (id_ej, ano, mes), a carga e o arquivo de origem.
--   3. Detectar reenvio pelo hash. O mesmo arquivo (SHA-256) carregado de novo
--      no mesmo escopo é reconhecido e registrado como reenvio, e a staging não
--      é duplicada.
--   4. Diagnosticar erro com a linha que falhou em mãos. Carga que falha no
--      banco registra a staging mesmo assim — o dado de gestão volta atrás
--      inteiro, a evidência do que se tentou gravar fica.
--
-- O papel `ingestao` também nasce aqui, porque as políticas destas duas tabelas
-- já falam dele. As políticas de escrita nas tabelas de gestão ficam em 11.
-- ============================================================================


-- ── O papel da carga ────────────────────────────────────────────────────────
--
-- A carga NÃO usa a service key, nem o dono das tabelas: os dois ignoram RLS, e
-- usá-los aqui abriria uma porta dos fundos no isolamento das fases 2-3. Ela
-- escreve com um papel próprio, sujeito às políticas como qualquer outro:
--
--   * sem BYPASSRLS, sem superusuário, dono de nada;
--   * só enxerga e grava a federação do claim da sessão — no modo nacional a
--     carga troca o claim federação a federação, dentro da mesma transação;
--   * NÃO tem DELETE em tabela nenhuma. "Não apague linha que deixou de vir" é
--     garantia de privilégio, não de disciplina de código.
--
-- O PostgREST não assume este papel (o `authenticator` do Supabase só troca
-- para anon/authenticated/service_role), então dar escrita a `ingestao` não dá
-- escrita a usuário nenhum da API — que continua só com SELECT (ver ADR-002).

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'ingestao') THEN
        CREATE ROLE ingestao NOLOGIN;
    END IF;

    -- Role de LOGIN, SÓ no laboratório — mesmo critério de `app_authenticated`
    -- em 00. A ausência de `supabase_auth_admin` é o sinal de que não estamos no
    -- Supabase hospedado (é o mesmo teste que 06 usa, ao contrário). Lá, quem
    -- for rodar a carga cria o próprio login com senha de verdade, fora do
    -- repositório.
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'supabase_auth_admin')
       AND NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'app_ingestao') THEN
        CREATE ROLE app_ingestao LOGIN PASSWORD 'app_ingestao' IN ROLE ingestao;
    END IF;
END
$$;

COMMENT ON ROLE ingestao IS 'Carga das exportações do Portal BJ. Sujeito a RLS, sem DELETE. Ver 10 e 11.';

-- As políticas leem o claim por auth.jwt(), que mora no schema `auth`.
GRANT USAGE ON SCHEMA auth   TO ingestao;
GRANT USAGE ON SCHEMA public TO ingestao;


-- ── ingestao_carga ──────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS ingestao_carga (
    id               BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    arquivo_nome     TEXT        NOT NULL,
    arquivo_hash     TEXT        NOT NULL CHECK (arquivo_hash ~ '^[0-9a-f]{64}$'),
    aba              TEXT        NOT NULL,
    -- A planilha não tem coluna de ano: ele vem de fora (--ano). Sem guardá-lo
    -- aqui, reprocessar a staging exigiria adivinhar o ano de novo.
    ano              INTEGER     NOT NULL,
    exportado_em     DATE,                      -- derivado do nome do arquivo; NULL se não der
    carregado_em     TIMESTAMPTZ NOT NULL DEFAULT now(),
    carregado_por    BIGINT      REFERENCES usuario(id),   -- NULL: a CLI não tem usuário
    origem           TEXT        NOT NULL CHECK (origem IN ('cli', 'upload')),
    escopo           TEXT        NOT NULL CHECK (escopo IN ('nacional', 'federacao')),
    federacao_id     BIGINT      REFERENCES federacao(id), -- NULL quando o escopo é nacional
    status           TEXT        NOT NULL CHECK (status IN ('sucesso', 'erro', 'rejeitada')),
    linhas_lidas     INTEGER     CHECK (linhas_lidas     >= 0),
    linhas_aplicadas INTEGER     CHECK (linhas_aplicadas >= 0),
    linhas_ignoradas INTEGER     CHECK (linhas_ignoradas >= 0),
    mensagem_erro    TEXT,
    -- Carga anterior, bem-sucedida, com o mesmo hash no mesmo escopo. Quando
    -- preenchido, esta carga não gravou staging: as linhas são as de lá.
    reenvio_de       BIGINT      REFERENCES ingestao_carga(id),
    -- O relatório da carga: novas/atualizadas por tabela, avisos e o
    -- diagnóstico de acumulado (9.23). Guardado para que a TENDÊNCIA desses
    -- números entre uma exportação e outra possa ser vista — um diagnóstico que
    -- só aparece no terminal não mostra que piorou.
    resumo           JSONB,

    -- Escopo e tenant andam juntos: nacional ⇔ sem federação.
    CONSTRAINT ingestao_carga_escopo_coerente
        CHECK ((escopo = 'nacional') = (federacao_id IS NULL)),
    -- Falha sem explicação não ajuda ninguém.
    CONSTRAINT ingestao_carga_falha_explicada
        CHECK (status = 'sucesso' OR mensagem_erro IS NOT NULL)
);

COMMENT ON TABLE  ingestao_carga              IS 'Uma linha por arquivo processado, com sucesso ou não. Proveniência de toda carga.';
COMMENT ON COLUMN ingestao_carga.federacao_id IS 'Tenant da carga. NULL = carga nacional, registro de operação da plataforma: nenhuma federação a enxerga.';
COMMENT ON COLUMN ingestao_carga.reenvio_de   IS 'Carga anterior com o mesmo arquivo (hash) no mesmo escopo. Staging não duplicada.';

CREATE INDEX IF NOT EXISTS idx_ingestao_carga_hash      ON ingestao_carga (arquivo_hash);
CREATE INDEX IF NOT EXISTS idx_ingestao_carga_federacao ON ingestao_carga (federacao_id, carregado_em);


-- ── ingestao_staging_ej ─────────────────────────────────────────────────────
--
-- A linha inteira fica em `linha` (jsonb), com as chaves exatamente como vieram
-- no cabeçalho — menos E_MAIL, SITE e FACEBOOK, que o leitor descarta antes de
-- tudo (dado de contato sem uso no portal).
--
-- As colunas tipadas são GERADAS a partir de `linha`, não gravadas em paralelo:
-- assim a versão tipada e a bruta não têm como discordar. São o valor ANTES da
-- transformação — CSAT 0 continua 0 aqui, cluster 0 continua 0, acumulado vazio
-- continua NULL. As regras moram em app/ingestao/transform.py, e reprocessar é
-- reaplicá-las sobre isto.
--
-- Os nomes seguem a coluna da planilha em minúsculas, com duas exceções: ID
-- vira `id_ej` (é a chave do portal, e `id` já é a PK daqui), e o par de
-- colunas de cluster, cujo nome muda com o ano, vira `cluster_ano_anterior` /
-- `cluster_ano`, relativos à coluna `ano`.

CREATE TABLE IF NOT EXISTS ingestao_staging_ej (
    id            BIGINT  GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    carga_id      BIGINT  NOT NULL REFERENCES ingestao_carga(id),
    -- Resolvido a partir de FEDERACAO na carga. É o predicado de RLS. NOT NULL:
    -- só entra na staging linha que foi roteada para um tenant conhecido.
    federacao_id  BIGINT  NOT NULL REFERENCES federacao(id),
    linha_arquivo INTEGER NOT NULL,    -- linha no Excel (o cabeçalho é a linha 1)
    ano           INTEGER NOT NULL,
    linha         JSONB   NOT NULL,

    -- identificação
    id_ej                BIGINT  GENERATED ALWAYS AS ((linha ->> 'ID')::bigint) STORED,
    empresa_junior       TEXT    GENERATED ALWAYS AS (linha ->> 'EMPRESA_JUNIOR') STORED,
    cnpj                 TEXT    GENERATED ALWAYS AS (linha ->> 'CNPJ') STORED,
    federacao            TEXT    GENERATED ALWAYS AS (linha ->> 'FEDERACAO') STORED,
    nucleos              TEXT    GENERATED ALWAYS AS (linha ->> 'NUCLEOS') STORED,
    e_federada           TEXT    GENERATED ALWAYS AS (linha ->> 'E_FEDERADA') STORED,
    ano_de_federacao     INTEGER GENERATED ALWAYS AS ((linha ->> 'ANO_DE_FEDERACAO')::integer) STORED,
    estado               TEXT    GENERATED ALWAYS AS (linha ->> 'ESTADO') STORED,
    cidade               TEXT    GENERATED ALWAYS AS (linha ->> 'CIDADE') STORED,
    universidade         TEXT    GENERATED ALWAYS AS (linha ->> 'UNIVERSIDADE') STORED,
    cursos               TEXT    GENERATED ALWAYS AS (linha ->> 'CURSOS') STORED,
    membros              INTEGER GENERATED ALWAYS AS ((linha ->> 'MEMBROS')::integer) STORED,

    -- cluster
    cluster_ano_anterior INTEGER GENERATED ALWAYS AS ((linha ->> ('CLUSTER_' || (ano - 1)::text))::integer) STORED,
    cluster_ano          INTEGER GENERATED ALWAYS AS ((linha ->> ('CLUSTER_' || ano::text))::integer) STORED,

    -- metas
    meta_de_revenue              NUMERIC GENERATED ALWAYS AS ((linha ->> 'META_DE_REVENUE')::numeric) STORED,
    meta_de_impact_projects      INTEGER GENERATED ALWAYS AS ((linha ->> 'META_DE_IMPACT_PROJECTS')::integer) STORED,
    meta_de_mej_engaged_members  NUMERIC GENERATED ALWAYS AS ((linha ->> 'META_DE_MEJ_ENGAGED_MEMBERS')::numeric) STORED,
    meta_de_collaborative_rate   NUMERIC GENERATED ALWAYS AS ((linha ->> 'META_DE_COLLABORATIVE_RATE')::numeric) STORED,
    meta_de_length_of_stay       NUMERIC GENERATED ALWAYS AS ((linha ->> 'META_DE_LENGTH_OF_STAY')::numeric) STORED,
    meta_de_csat                 NUMERIC GENERATED ALWAYS AS ((linha ->> 'META_DE_CSAT')::numeric) STORED,
    meta_de_di_politics          INTEGER GENERATED ALWAYS AS ((linha ->> 'META_DE_DI_POLITICS')::integer) STORED,

    -- fato mensal
    mes                                     INTEGER GENERATED ALWAYS AS ((linha ->> 'MES')::integer) STORED,
    faturamento                             NUMERIC GENERATED ALWAYS AS ((linha ->> 'FATURAMENTO')::numeric) STORED,
    faturamento_acumulado                   NUMERIC GENERATED ALWAYS AS ((linha ->> 'FATURAMENTO_ACUMULADO')::numeric) STORED,
    faturamento_colaborativo                NUMERIC GENERATED ALWAYS AS ((linha ->> 'FATURAMENTO_COLABORATIVO')::numeric) STORED,
    faturamento_colaborativo_acumulado      NUMERIC GENERATED ALWAYS AS ((linha ->> 'FATURAMENTO_COLABORATIVO_ACUMULADO')::numeric) STORED,
    contratos                               INTEGER GENERATED ALWAYS AS ((linha ->> 'CONTRATOS')::integer) STORED,
    solucoes                                INTEGER GENERATED ALWAYS AS ((linha ->> 'SOLUCOES')::integer) STORED,
    csat                                    NUMERIC GENERATED ALWAYS AS ((linha ->> 'CSAT')::numeric) STORED,
    porcentagem_de_coleta_csat              NUMERIC GENERATED ALWAYS AS ((linha ->> 'PORCENTAGEM_DE_COLETA_CSAT')::numeric) STORED,
    quantidade_de_membros_engajados_com_mej INTEGER GENERATED ALWAYS AS ((linha ->> 'QUANTIDADE_DE_MEMBROS_ENGAJADOS_COM_MEJ')::integer) STORED,

    UNIQUE (carga_id, linha_arquivo)
);

COMMENT ON TABLE  ingestao_staging_ej       IS 'Linha bruta da planilha de EJ, antes de qualquer transformação. Colunas tipadas são geradas de `linha`.';
COMMENT ON COLUMN ingestao_staging_ej.linha IS 'A linha inteira, com as chaves do cabeçalho original. Sem E_MAIL, SITE e FACEBOOK.';

-- Tenant na frente, como em todo índice novo sob RLS (ver 04).
CREATE INDEX IF NOT EXISTS idx_staging_ej_federacao_carga ON ingestao_staging_ej (federacao_id, carga_id);
-- "De onde veio este número?": do fato mensal para a linha que o trouxe.
CREATE INDEX IF NOT EXISTS idx_staging_ej_origem          ON ingestao_staging_ej (id_ej, ano, mes);


-- ── RLS ─────────────────────────────────────────────────────────────────────
--
-- As duas entram com RLS ligada, como toda tabela deste schema (ver 07).
--
-- A regra de ouro de `ingestao_carga`: carga NACIONAL (federacao_id IS NULL) é
-- registro de operação da plataforma e NÃO aparece para federação nenhuma. A
-- comparação `federacao_id = <claim>` já não casa NULL com nada (NULL = x é
-- NULL, e NULL não é TRUE); o `federacao_id IS NOT NULL` explícito está lá para
-- que isso continue verdade se alguém um dia trocar `=` por `IS NOT DISTINCT
-- FROM` — que casaria NULL com "token sem tenant" e entregaria as cargas
-- nacionais a quem não provou federação nenhuma.

ALTER TABLE ingestao_carga      ENABLE ROW LEVEL SECURITY;
ALTER TABLE ingestao_staging_ej ENABLE ROW LEVEL SECURITY;

-- Leitura pelos usuários da API: só a própria federação.
CREATE POLICY ingestao_carga_select_proprio_tenant ON ingestao_carga
    FOR SELECT TO authenticated
    USING (
        federacao_id IS NOT NULL
        AND federacao_id = nullif(auth.jwt() ->> 'federacao_id', '')::bigint
    );

CREATE POLICY ingestao_staging_ej_select_proprio_tenant ON ingestao_staging_ej
    FOR SELECT TO authenticated
    USING (federacao_id = nullif(auth.jwt() ->> 'federacao_id', '')::bigint);

GRANT SELECT ON ingestao_carga, ingestao_staging_ej TO authenticated;

-- A carga, por sua vez, lê e escreve a carga do claim da sessão. A única
-- exceção a "sempre um tenant" é a linha da carga nacional, que o papel
-- `ingestao` só alcança com o claim explícito `escopo = nacional` — nunca por
-- ausência de claim. É o registro da operação; o dado das federações continua
-- sendo gravado sob o claim de cada uma (ver app/ingestao/carga.py).
CREATE POLICY ingestao_carga_escrita_ingestao ON ingestao_carga
    FOR ALL TO ingestao
    USING (
        (federacao_id IS NOT NULL AND federacao_id = nullif(auth.jwt() ->> 'federacao_id', '')::bigint)
        OR (federacao_id IS NULL AND auth.jwt() ->> 'escopo' = 'nacional')
    )
    WITH CHECK (
        (federacao_id IS NOT NULL AND federacao_id = nullif(auth.jwt() ->> 'federacao_id', '')::bigint)
        OR (federacao_id IS NULL AND auth.jwt() ->> 'escopo' = 'nacional')
    );

CREATE POLICY ingestao_staging_ej_escrita_ingestao ON ingestao_staging_ej
    FOR ALL TO ingestao
    USING      (federacao_id = nullif(auth.jwt() ->> 'federacao_id', '')::bigint)
    WITH CHECK (federacao_id = nullif(auth.jwt() ->> 'federacao_id', '')::bigint);

-- FOR ALL nas políticas acima não dá DELETE a ninguém: quem decide o verbo é o
-- GRANT, e DELETE não é concedido. Staging não tem UPDATE: linha bruta não muda.
GRANT SELECT, INSERT, UPDATE ON ingestao_carga      TO ingestao;
GRANT SELECT, INSERT         ON ingestao_staging_ej TO ingestao;



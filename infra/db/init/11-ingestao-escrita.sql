-- ============================================================================
-- 11 — A carga escreve sob RLS: PKs geradas, núcleo por nome e as políticas de
--      escrita do papel `ingestao`
--
-- Até aqui NENHUM papel sujeito a RLS escrevia em tabela nenhuma: 07 só criou
-- políticas de SELECT, e toda carga era feita pelo dono das tabelas, que passa
-- por cima da RLS. Este arquivo abre escrita para UM papel — `ingestao`, criado
-- em 10 —, e só para as colunas que a carga da planilha de EJ de fato grava.
--
-- O QUE CONTINUA FECHADO, DE PROPÓSITO:
--   * `authenticated` (usuário da API) segue só com SELECT. Escrita pela API
--     entra com a regra de papel, na porta HTTP — não aqui (ver ADR-002).
--   * DELETE não é concedido a `ingestao` em tabela nenhuma. Uma EJ que some da
--     exportação não é ordem de apagar histórico, e o banco garante isso.
--   * UPDATE é concedido POR COLUNA. `comunidade`, `status`, `foto_url`,
--     `projetos_totais` e as colunas `_legado` não vêm da planilha, e a carga
--     não tem como sobrescrevê-las nem por engano.
--   * `federacao_id` de uma EJ não é atualizável pela carga: mudar uma EJ de
--     federação exige decisão humana, e a carga falha alto quando esbarra nisso.
--   * Metas e monitoramento: só o nível EJ (`id_ej`). Núcleo e federação entram
--     com a ingestão das planilhas deles, que é outra fase.
-- ============================================================================


-- ── 1. PKs que o banco gera ─────────────────────────────────────────────────
--
-- Em 01 (derivado da documentação, não de dump) `empresa_junior.id`, `metas.id`
-- e `monitoramento.id` são BIGINT PRIMARY KEY sem default — nada gera o id de
-- uma linha nova. No Supabase real elas provavelmente já são identity
-- `[CONFIRMAR]` com infra/db/queries/02-inventario-schema.sql. Por isso o bloco
-- só age quando a coluna não tem identity NEM default, e começa depois do
-- maior id existente.
--
-- BY DEFAULT, não ALWAYS: seed e teste continuam podendo informar o id
-- (tests/test_rls.py usa ids fixos a partir de 900.000).

DO $$
DECLARE
    alvo  record;
    maior bigint;
BEGIN
    FOR alvo IN
        SELECT c.table_name
          FROM information_schema.columns c
         WHERE c.table_schema = 'public'
           AND c.column_name  = 'id'
           AND c.table_name IN ('empresa_junior', 'metas', 'monitoramento')
           AND c.is_identity  = 'NO'
           AND c.column_default IS NULL
    LOOP
        EXECUTE format('ALTER TABLE %I ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY', alvo.table_name);
        EXECUTE format('SELECT coalesce(max(id), 0) FROM %I', alvo.table_name) INTO maior;
        PERFORM setval(pg_get_serial_sequence(alvo.table_name, 'id'), maior + 1, false);
    END LOOP;
END
$$;


-- ── 2. Núcleo: resolvido por nome, criado quando falta ──────────────────────
--
-- A planilha de EJ traz o NOME do núcleo ("Núcleo Maringá"), não o id. A carga
-- resolve por (federação, nome) — daí a unicidade abaixo, que também impede
-- dois "Núcleo Centro" na mesma federação.
--
-- `nucleo.id` continua sendo, por regra, o ID do Portal BJ (03), e os 26 núcleos
-- de hoje entram com o ID real em 12. A identity existe só para o caso que a
-- carga precisa cobrir: núcleo que aparece na planilha e ainda não está
-- cadastrado. Ela começa em 100.000 para que um id gerado nunca se confunda com
-- um do Portal BJ (hoje de 9 a 46) e fique fora da faixa que tests/test_rls.py
-- apaga na limpeza (>= 900.000). A carga avisa toda vez que cria um: esse id
-- precisa ser reconciliado quando a planilha de núcleos entrar.

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
         WHERE table_schema = 'public' AND table_name = 'nucleo'
           AND column_name = 'id' AND is_identity = 'YES'
    ) THEN
        ALTER TABLE nucleo ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (START WITH 100000);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
         WHERE conrelid = 'nucleo'::regclass AND conname = 'nucleo_federacao_nome_unico'
    ) THEN
        ALTER TABLE nucleo ADD CONSTRAINT nucleo_federacao_nome_unico UNIQUE (federacao_id, nome);
    END IF;
END
$$;


-- ── 3. Políticas de escrita do papel `ingestao` ─────────────────────────────
--
-- O predicado é o mesmo das políticas de leitura de 07: o tenant da linha tem
-- de ser o `federacao_id` do claim. A carga define o claim antes de cada fatia
-- (`set_config('request.jwt.claims', ...)`, como o PostgREST faz por requisição),
-- então uma linha de FEJEPAR gravada sob o claim de FEJEPE é recusada pelo
-- banco — mesmo que o filtro em Python tenha falhado.
--
-- FOR ALL com USING e WITH CHECK iguais: a mesma regra vale para enxergar (o
-- UPDATE ... FROM e o NOT EXISTS da carga precisam ler), inserir e atualizar.

-- federacao: catálogo. A carga precisa resolver o nome de TODAS para rotear as
-- linhas e para recusar federação desconhecida. Só id, slug e nome.
CREATE POLICY federacao_select_ingestao ON federacao
    FOR SELECT TO ingestao
    USING (true);

GRANT SELECT (id, slug, nome) ON federacao TO ingestao;


CREATE POLICY nucleo_escrita_ingestao ON nucleo
    FOR ALL TO ingestao
    USING      (federacao_id = nullif(auth.jwt() ->> 'federacao_id', '')::bigint)
    WITH CHECK (federacao_id = nullif(auth.jwt() ->> 'federacao_id', '')::bigint);

GRANT SELECT                   ON nucleo TO ingestao;
GRANT INSERT (federacao_id, nome) ON nucleo TO ingestao;   -- o id, a identity gera


CREATE POLICY empresa_junior_escrita_ingestao ON empresa_junior
    FOR ALL TO ingestao
    USING      (federacao_id = nullif(auth.jwt() ->> 'federacao_id', '')::bigint)
    WITH CHECK (federacao_id = nullif(auth.jwt() ->> 'federacao_id', '')::bigint);

GRANT SELECT ON empresa_junior TO ingestao;
GRANT INSERT (id_ej, nome, cnpj, ano_federacao, estado, cidade, universidade, curso,
              federacao_id, nucleo_id)
    ON empresa_junior TO ingestao;
GRANT UPDATE (nome, cnpj, ano_federacao, estado, cidade, universidade, curso, nucleo_id)
    ON empresa_junior TO ingestao;


CREATE POLICY metas_escrita_ingestao ON metas
    FOR ALL TO ingestao
    USING (
        EXISTS (
            SELECT 1 FROM empresa_junior ej
             WHERE ej.id_ej = metas.id_ej
               AND ej.federacao_id = nullif(auth.jwt() ->> 'federacao_id', '')::bigint
        )
    )
    WITH CHECK (
        EXISTS (
            SELECT 1 FROM empresa_junior ej
             WHERE ej.id_ej = metas.id_ej
               AND ej.federacao_id = nullif(auth.jwt() ->> 'federacao_id', '')::bigint
        )
    );

GRANT SELECT ON metas TO ingestao;
GRANT INSERT (id_ej, ano, meta_faturamento, meta_taxa_colaboracao, meta_csat,
              meta_projetos_impacto, meta_pdi, meta_engajamento_mej)
    ON metas TO ingestao;
GRANT UPDATE (meta_faturamento, meta_taxa_colaboracao, meta_csat,
              meta_projetos_impacto, meta_pdi, meta_engajamento_mej)
    ON metas TO ingestao;


CREATE POLICY monitoramento_escrita_ingestao ON monitoramento
    FOR ALL TO ingestao
    USING (
        EXISTS (
            SELECT 1 FROM empresa_junior ej
             WHERE ej.id_ej = monitoramento.id_ej
               AND ej.federacao_id = nullif(auth.jwt() ->> 'federacao_id', '')::bigint
        )
    )
    WITH CHECK (
        EXISTS (
            SELECT 1 FROM empresa_junior ej
             WHERE ej.id_ej = monitoramento.id_ej
               AND ej.federacao_id = nullif(auth.jwt() ->> 'federacao_id', '')::bigint
        )
    );

-- `projetos_totais` fica de fora: a coluna SOLUCOES da planilha é valor do mês,
-- não total, e gravá-la ali mudaria o KPI "Projetos" do perfil (decisão de
-- 21/09; ver docs/regras-de-negocio.md, 9.3).
GRANT SELECT ON monitoramento TO ingestao;
GRANT INSERT (id_ej, ano, mes, faturamento_mes, faturamento_acumulado,
              faturamento_colab_mes, faturamento_colab_acumulado,
              projetos_vendidos_mes, csat, numero_membros, membros_engajados_mes)
    ON monitoramento TO ingestao;
GRANT UPDATE (faturamento_mes, faturamento_acumulado,
              faturamento_colab_mes, faturamento_colab_acumulado,
              projetos_vendidos_mes, csat, numero_membros, membros_engajados_mes)
    ON monitoramento TO ingestao;


CREATE POLICY cluster_historico_escrita_ingestao ON cluster_historico
    FOR ALL TO ingestao
    USING (
        EXISTS (
            SELECT 1 FROM empresa_junior ej
             WHERE ej.id_ej = cluster_historico.id_ej
               AND ej.federacao_id = nullif(auth.jwt() ->> 'federacao_id', '')::bigint
        )
    )
    WITH CHECK (
        EXISTS (
            SELECT 1 FROM empresa_junior ej
             WHERE ej.id_ej = cluster_historico.id_ej
               AND ej.federacao_id = nullif(auth.jwt() ->> 'federacao_id', '')::bigint
        )
    );

GRANT SELECT                       ON cluster_historico TO ingestao;
GRANT INSERT (id_ej, ano, cluster) ON cluster_historico TO ingestao;
GRANT UPDATE (cluster)             ON cluster_historico TO ingestao;



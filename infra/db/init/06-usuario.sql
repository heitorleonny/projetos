-- ============================================================================
-- 06 — Tabela `usuario` e o hook que leva o tenant para dentro do JWT
--
-- O levantamento (docs/levantamento-semana1-multitenant.md, seção 5) apontou o
-- bloqueio: não existe tabela de vínculo usuário ↔ federação. Sem ela,
-- `federacao_id` é coluna decorativa — a política de RLS não tem contra o que
-- comparar, porque o JWT não carrega tenant nenhum.
--
-- Esta tabela é a fonte da verdade desse vínculo. O hook abaixo é só a correia
-- que copia `federacao_id` e `papel` daqui para os claims do token, no login.
-- O sentido é sempre este: banco → JWT. NUNCA JWT → banco.
--
-- ESCOPO: isto é desenho de tabela. Não há convite por e-mail, não há criação
-- de usuário, não há vínculo real com o Supabase Auth (a coluna existe e fica
-- NULL), não há enforcement de `plano.limite_usuarios`.
-- ============================================================================


-- ── usuario ─────────────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS usuario (
    -- Diferente de `federacao` e `nucleo`, `usuario` não tem ID de origem no
    -- Portal BJ para reaproveitar. IDENTITY BY DEFAULT: o banco gera, mas
    -- seed e teste ainda podem informar o id explicitamente.
    id              BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    federacao_id    BIGINT      NOT NULL REFERENCES federacao(id),
    nome            TEXT        NOT NULL,
    email           TEXT        NOT NULL UNIQUE,
    papel           TEXT        NOT NULL CHECK (papel IN ('admin', 'membro')),
    conta_principal BOOLEAN     NOT NULL DEFAULT false,
    ativo           BOOLEAN     NOT NULL DEFAULT true,
    -- Vínculo com `auth.users.id` do Supabase Auth. Fica NULL até alguém
    -- conectar os dois mundos de verdade; sem ele o hook não acha ninguém.
    auth_user_id    UUID        UNIQUE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE  usuario                 IS 'Usuário de uma federação. Fonte da verdade do vínculo usuário ↔ tenant e do papel.';
COMMENT ON COLUMN usuario.papel           IS 'admin ou membro. Só estes dois — os nomes antigos (gestor, visualizador) saíram de circulação.';
COMMENT ON COLUMN usuario.conta_principal IS 'Conta responsável pela federação. No máximo uma por federação, garantido por índice único parcial.';
COMMENT ON COLUMN usuario.auth_user_id    IS 'auth.users.id do Supabase Auth. NULL hoje: o vínculo real ainda não foi feito.';

-- No máximo UMA conta principal por federação — garantido pelo banco, não por
-- convenção de aplicação. Índice parcial: as linhas com conta_principal = false
-- ficam fora do índice e não competem entre si.
CREATE UNIQUE INDEX IF NOT EXISTS ux_usuario_conta_principal
    ON usuario (federacao_id) WHERE conta_principal;

CREATE INDEX IF NOT EXISTS idx_usuario_federacao ON usuario (federacao_id);


-- ── Custom Access Token Hook ────────────────────────────────────────────────
--
-- Formato do Supabase (Auth Hooks → Customize Access Token): a função recebe
-- um `event` jsonb com `user_id` e `claims`, e devolve o MESMO objeto com
-- `claims` alterado. Não inventar formato próprio aqui: quem chama é o GoTrue,
-- e ele espera exatamente esta forma.
--
-- Por que grava o tenant em DOIS lugares dentro de `claims`:
--   * no topo (`claims.federacao_id`) — é de lá que `auth.jwt()->>'federacao_id'`
--     lê dentro das políticas de RLS (07-rls-policies.sql);
--   * dentro de `claims.app_metadata` — é de lá que o backend lê, porque
--     `sb.auth.get_user(token).user.app_metadata` só enxerga esse ramo
--     (app/dependencies.py).
-- São dois leitores diferentes do mesmo fato; duplicar o valor é mais barato
-- que fazer um dos dois procurar no lugar do outro.
--
-- ATENÇÃO: esta função NÃO FAZ NADA SOZINHA. Nem aqui, nem no Supabase. Ela só
-- roda depois que alguém ATIVA O GATILHO MANUALMENTE no Dashboard do projeto:
--   Authentication → Hooks → Customize Access Token (Beta) → selecionar
--   `public.custom_access_token_hook` → Enable.
-- Isso é ação de operador, feita uma vez, quando (e se) o projeto for de fato
-- conectado. Até lá nenhum JWT emitido carrega `federacao_id`.

CREATE OR REPLACE FUNCTION public.custom_access_token_hook(event jsonb)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    claims        jsonb;
    app_metadata  jsonb;
    v_federacao_id bigint;
    v_papel        text;
BEGIN
    SELECT u.federacao_id, u.papel
      INTO v_federacao_id, v_papel
      FROM public.usuario u
     WHERE u.auth_user_id = (event ->> 'user_id')::uuid
       AND u.ativo;

    claims := coalesce(event -> 'claims', '{}'::jsonb);

    -- Usuário sem vínculo (ou inativo) sai com o token intacto, sem tenant.
    -- Consequência desejada: as políticas de RLS não casam com nada e ele não
    -- enxerga linha nenhuma. Falha fechado.
    IF v_federacao_id IS NULL THEN
        RETURN event;
    END IF;

    app_metadata := coalesce(claims -> 'app_metadata', '{}'::jsonb);
    app_metadata := jsonb_set(app_metadata, '{federacao_id}', to_jsonb(v_federacao_id));
    app_metadata := jsonb_set(app_metadata, '{papel}',        to_jsonb(v_papel));

    claims := jsonb_set(claims, '{federacao_id}',  to_jsonb(v_federacao_id));
    claims := jsonb_set(claims, '{papel}',         to_jsonb(v_papel));
    claims := jsonb_set(claims, '{app_metadata}',  app_metadata);

    RETURN jsonb_set(event, '{claims}', claims);
END;
$$;

COMMENT ON FUNCTION public.custom_access_token_hook(jsonb) IS 'Copia federacao_id e papel de `usuario` para os claims do JWT. Inerte até o hook ser ativado no Dashboard.';

-- Permissões do hook. Quem executa é o `supabase_auth_admin`, role que só
-- existe no Supabase hospedado — daí o bloco condicional: no laboratório local
-- ele simplesmente não roda.
-- O REVOKE é a parte que importa em segurança: sem ele, um usuário autenticado
-- poderia chamar a função (que é SECURITY DEFINER) com um user_id qualquer.
REVOKE EXECUTE ON FUNCTION public.custom_access_token_hook(jsonb) FROM PUBLIC, anon, authenticated;

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'supabase_auth_admin') THEN
        EXECUTE 'GRANT USAGE ON SCHEMA public TO supabase_auth_admin';
        EXECUTE 'GRANT EXECUTE ON FUNCTION public.custom_access_token_hook(jsonb) TO supabase_auth_admin';
        EXECUTE 'GRANT SELECT ON TABLE public.usuario TO supabase_auth_admin';
    END IF;
END
$$;
